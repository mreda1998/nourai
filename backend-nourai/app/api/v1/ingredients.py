# ─── Response schemas ─────────────────────────────────────────────────────────

class QualityFlag(BaseModel):
    code: str
    label: str               # caveat tag shown to readers, e.g. "Small study (34 people)"


class EvidenceRecord(BaseModel):
    id: str
    pmid: str | None
    title: str | None
    journal: str | None
    year: int | None
    study_type: str | None
    population: str | None
    sample_size: int | None
    finding: str
    direction: str           # benefit | risk | neutral | mixed
    effect_size: str | None  # strong | moderate | weak
    confidence: str          # high | moderate | low
    concern_tags: list[str]
    goal_tags: list[str]

    # How the study was done — null for studies from the pre-claims pipeline
    method_summary: str | None = None
    caveat: str | None = None
    quality_score: float | None = None   # 0-1
    quality_tier: str | None = None      # high | moderate | low | very_low
    quality_flags: list[QualityFlag] = []
    intervention_form: str | None = None
    dose_amount: float | None = None
    dose_unit: str | None = None
    dose_frequency: str | None = None
    duration_weeks: float | None = None
    outcome_type: str | None = None      # clinical | patient_reported | biomarker | mechanistic | safety


class ClaimStudy(BaseModel):
    evidence_id: str
    stance: str              # supports | refutes | inconclusive
    relevance: str           # direct | indirect


class ClaimRecord(BaseModel):
    id: str
    kind: str                # benefit | safety
    claim: str
    why_people_believe: str | None
    verdict: str | None      # strong | moderate | limited | mixed | unlikely | insufficient
    certainty: str | None    # high | moderate | low | very_low
    certainty_reasons: list[str]
    reality: str | None
    effect_size: str | None
    applies_to: str | None
    avoid_if: str | None
    dose_note: str | None
    key_pmids: list[str]
    study_count: int
    studies: list[ClaimStudy]  # strongest first


class BioDomainScore(BaseModel):
    biodomain: str
    direction: str              # benefit | harm | neutral | mixed
    magnitude: float            # 0.0 – 1.0
    confidence: str             # high | moderate | low
    dose_dependent: bool
    effective_dose_low: float | None
    effective_dose_high: float | None
    dose_unit: str | None
    evidence_count: int
    notes: str | None


class FoundInProduct(BaseModel):
    id: str
    name: str
    brand: str | None
    category: str
    subcategory: str | None
    image_url: str | None
    amount: str | None       # e.g. "10%" or "400mg"
    status: str | None       # clean | watch | avoid


class IngredientDetail(BaseModel):
    id: str
    canonical_name: str
    category: str
    description: str | None
    mechanism_summary: str | None

    # Belief vs. reality — the core NourAI differentiator
    common_belief: str | None
    evidence_reality: str | None

    # Dosage / safety
    typical_dose_range: str | None
    recommended_daily: str | None
    upper_limit: str | None
    side_effects: list[str]
    contraindications: list[str]
    drug_interactions: list[str]

    # Research summary
    evidence_level: str | None   # strong | moderate | limited | insufficient
    research_status: str

    # Mechanism illustration URL (generated by research agent)
    mechanism_image_url: str | None

    # 2D chemical structure image URL (from PubChem, re-hosted on Supabase)
    structure_image_url: str | None

    # What people believe it does, each judged from its studies (empty before claim-based research)
    claims: list[ClaimRecord] = []

    # Evidence records — strongest first (see _sort_evidence)
    evidence: list[EvidenceRecord]

    # Biodomain impact scores — per-domain effect computed by the research agent
    biodomain_scores: list[BioDomainScore]

    # Products in our DB that contain this ingredient
    found_in: list[FoundInProduct]

    # Peptide-specific fields (null for non-peptide ingredients)
    us_regulatory_status: str | None = None
    wada_status: str | None = None
    admin_routes: list[str] | None = None
    admin_route_notes: str | None = None
    cycle_length_weeks: int | None = None
    washout_weeks: int | None = None
    cycling_notes: str | None = None


class IngredientListItem(BaseModel):
    id: str
    canonical_name: str
    category: str
    description: str | None
    evidence_level: str | None
    research_status: str


class IngredientSearchResponse(BaseModel):
    ingredients: list[IngredientListItem]
    total: int


# ─── Helpers ──────────────────────────────────────────────────────────────────

_CONFIDENCE_ORDER = {"high": 0, "moderate": 1, "low": 2}


def _sort_evidence(records: list[IngredientEvidence]) -> list[IngredientEvidence]:
    """Appraised studies by weight; older, unappraised ones after, by confidence then year."""
    return sorted(
        records,
        key=lambda e: (
            e.quality_score is None,
            -(e.quality_score or 0),
            _CONFIDENCE_ORDER.get(e.confidence, 9),
            -(e.year or 0),
        ),
    )


def _claim_record(claim: IngredientClaim) -> ClaimRecord:
    links = sorted(claim.evidence_links, key=lambda link: -(link.evidence.quality_score or 0))
    return ClaimRecord(
        id=str(claim.id),
        kind=claim.kind,
        claim=claim.claim,
        why_people_believe=claim.why_people_believe,
        verdict=claim.verdict,
        certainty=claim.certainty,
        certainty_reasons=claim.certainty_reasons or [],
        reality=claim.reality,
        effect_size=claim.effect_size,
        applies_to=claim.applies_to,
        avoid_if=claim.avoid_if,
        dose_note=claim.dose_note,
        key_pmids=claim.key_pmids or [],
        study_count=claim.study_count,
        studies=[
            ClaimStudy(evidence_id=str(link.evidence_id), stance=link.stance, relevance=link.relevance)
            for link in links
        ],
    )


# ─── Endpoints ────────────────────────────────────────────────────────────────

@router.get("/search", response_model=IngredientSearchResponse)
async def search_ingredients(
    q: str = Query(..., min_length=2, description="Search term (partial match on name or synonym)"),
    limit: int = Query(20, le=50),
    db: AsyncSession = Depends(get_db),
) -> Any:
    """
    Search canonical ingredients by name.

    Matches against canonical_name with a case-insensitive LIKE.
    Returns up to `limit` results ordered alphabetically.

    Used by:
      • Search tab when the user toggles to "Ingredients"
      • Any screen that needs ingredient autocomplete
    """
    pattern = f"%{q}%"
    stmt = (
        select(Ingredient)
        .where(Ingredient.canonical_name.ilike(pattern))
        .order_by(Ingredient.canonical_name)
        .limit(limit)
    )
    result = await db.execute(stmt)
    ingredients = result.scalars().all()

    # Also count total matches (for the UI to show "X results")
    count_stmt = (
        select(func.count())
        .select_from(Ingredient)
        .where(Ingredient.canonical_name.ilike(pattern))
    )
    total = (await db.execute(count_stmt)).scalar_one()

    return IngredientSearchResponse(
        ingredients=[
            IngredientListItem(
                id=str(ing.id),
                canonical_name=ing.canonical_name,
                category=ing.category,
                description=ing.description,
                evidence_level=ing.evidence_level,
                research_status=ing.research_status,
            )
            for ing in ingredients
        ],
        total=total,
    )


@router.get("/{ingredient_id}", response_model=IngredientDetail)
async def get_ingredient(
    ingredient_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
) -> Any:
    """
    Full ingredient deep dive.

    Returns:
      • Mechanism summary + description
      • Belief vs. reality (common_belief / evidence_reality)
      • Dosage and safety information
      • All synthesized PubMed evidence records, sorted by confidence
      • List of products in our DB that contain this ingredient

    Accessible from:
      • Product page → tapping an ingredient row
      • Search tab (ingredient search mode)
      • Any future surface (food log, stack, etc.)
    """
    # Load ingredient with evidence and biodomain scores in one query
    stmt = (
        select(Ingredient)
        .where(Ingredient.id == ingredient_id)
        .options(
            selectinload(Ingredient.evidence),
            selectinload(Ingredient.biodomain_scores),
            selectinload(Ingredient.claims)
            .selectinload(IngredientClaim.evidence_links)
            .selectinload(IngredientClaimEvidence.evidence),
        )
    )
    result = await db.execute(stmt)
    ingredient = result.scalar_one_or_none()

    if not ingredient:
        raise HTTPException(status_code=404, detail="Ingredient not found")

    # Load products that contain this ingredient, with product info joined.
    # We limit to 30 — enough to show a meaningful list without over-fetching.
    found_stmt = (
        select(ProductIngredient, Product)
        .join(Product, ProductIngredient.product_id == Product.id)
        .where(ProductIngredient.ingredient_id == ingredient_id)
        .order_by(Product.name)
        .limit(30)
    )
    found_result = await db.execute(found_stmt)
    found_rows = found_result.all()

    found_in = [
        FoundInProduct(
            id=str(product.id),
            name=product.name,
            brand=product.brand,
            category=product.category,
            subcategory=product.subcategory,
            image_url=product.image_url,
            amount=pi.amount,
            status=pi.status,
        )
        for pi, product in found_rows
    ]

    sorted_evidence = _sort_evidence(ingredient.evidence)

    biodomain_scores = [
        BioDomainScore(
            biodomain=bs.biodomain,
            direction=bs.direction,
            magnitude=bs.magnitude,
            confidence=bs.confidence,
            dose_dependent=bs.dose_dependent,
            effective_dose_low=bs.effective_dose_low,
            effective_dose_high=bs.effective_dose_high,
            dose_unit=bs.dose_unit,
            evidence_count=bs.evidence_count,
            notes=bs.notes,
        )
        for bs in sorted(ingredient.biodomain_scores, key=lambda s: s.biodomain)
    ]

    return IngredientDetail(
        id=str(ingredient.id),
        canonical_name=ingredient.canonical_name,
        category=ingredient.category,
        description=ingredient.description,
        mechanism_summary=ingredient.mechanism_summary,
        common_belief=ingredient.common_belief,
        evidence_reality=ingredient.evidence_reality,
        typical_dose_range=ingredient.typical_dose_range,
        recommended_daily=ingredient.recommended_daily,
        upper_limit=ingredient.upper_limit,
        side_effects=ingredient.side_effects or [],
        contraindications=ingredient.contraindications or [],
        drug_interactions=ingredient.drug_interactions or [],
        evidence_level=ingredient.evidence_level,
        research_status=ingredient.research_status,
        mechanism_image_url=ingredient.mechanism_image_url,
        structure_image_url=ingredient.structure_image_url,
        biodomain_scores=biodomain_scores,
        claims=[_claim_record(claim) for claim in ingredient.claims],
        evidence=[
            EvidenceRecord(
                id=str(ev.id),
                pmid=ev.pmid,
                title=ev.title,
                journal=ev.journal,
                year=ev.year,
                study_type=ev.study_type,
                population=ev.population,
                sample_size=ev.sample_size,
                finding=ev.finding,
                direction=ev.direction,
                effect_size=ev.effect_size,
                confidence=ev.confidence,
                concern_tags=ev.concern_tags or [],
                goal_tags=ev.goal_tags or [],
                method_summary=ev.method_summary,
                caveat=ev.caveat,
                quality_score=ev.quality_score,
                quality_tier=ev.quality_tier,
                quality_flags=[QualityFlag(**flag) for flag in ev.quality_flags or []],
                intervention_form=ev.intervention_form,
                dose_amount=ev.dose_amount,
                dose_unit=ev.dose_unit,
                dose_frequency=ev.dose_frequency,
                duration_weeks=ev.duration_weeks,
                outcome_type=ev.outcome_type,
            )
            for ev in sorted_evidence
        ],
        found_in=found_in,
        us_regulatory_status=ingredient.us_regulatory_status,
        wada_status=ingredient.wada_status,
        admin_routes=ingredient.admin_routes,
        admin_route_notes=ingredient.admin_route_notes,
        cycle_length_weeks=ingredient.cycle_length_weeks,
        washout_weeks=ingredient.washout_weeks,
        cycling_notes=ingredient.cycling_notes,
    )
