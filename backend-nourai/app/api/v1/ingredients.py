def _molecule(ingredient: Ingredient) -> dict | None:
    facts = molecule_facts(ingredient.smiles) if ingredient.smiles else None
    if not facts:
        return None
    return {"svg_path": f"/api/v1/ingredients/{ingredient.id}/structure.svg", **facts}

router = APIRouter()


# ─── Response schemas ─────────────────────────────────────────────────────────

